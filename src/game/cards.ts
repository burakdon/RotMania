import type { Ability, Bag, Brainrot, BrainrotType, Res, ToyRecipe } from './types';

const LETTER: Record<string, Res> = { G: 'grass', C: 'coolant', P: 'pcb', L: 'glitter', W: 'copper' };
const bag = (s: string): Bag => {
  const out: Bag = {};
  for (const ch of s) out[LETTER[ch]] = (out[LETTER[ch]] ?? 0) + 1;
  return out;
};

function b(id: string, name: string, type: BrainrotType, cost: string, strength: number, ability: Ability | undefined, flavor: string, toy: ToyRecipe): Brainrot {
  return { id, name, type, cost: bag(cost), strength, ability, flavor, toy };
}

