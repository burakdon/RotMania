// The brainrot deck. Every card is a unique figure. Edit freely: the engine only reads these fields.
// cost letters: G grass · B bread · V vinyl · Y yarn · P paper · * any
// rows letters: O Outside · W Workshop · C Group Chat
import type { Card, CostItem, Effect, Power, Row, ToyRecipe, Trigger, Vibe } from './types';

const COST: Record<string, CostItem> = { G: 'grass', B: 'bread', V: 'vinyl', Y: 'yarn', P: 'paper', '*': 'any' };
const ROWL: Record<string, Row> = { O: 0, W: 1, C: 2 };

const woke = (fx: Effect): Power => ({ when: 'woke', fx });
const each = (fx: Effect): Power => ({ when: 'each', fx });
const finale = (fx: Effect): Power => ({ when: 'finale', fx });
const meanwhile = (on: Trigger, fx: Effect, vibe?: Vibe): Power => ({ when: 'meanwhile', on, fx, vibe });
const whenJuice = (fx: Effect): Power => ({ when: 'whenever', on: 'youJuice', fx });

function c(
  id: string, name: string, vibe: Vibe, rows: string, cost: string, aura: number, cap: number, rot: number,
  power: Power | undefined, flavor: string, toy: ToyRecipe,
): Card {
  return {
    id, name, vibe, aura, cap, rot, power, flavor, toy,
    rows: [...rows].map((r) => ROWL[r]),
    cost: [...cost].map((l) => COST[l]),
  };
}

